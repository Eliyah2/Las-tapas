-- RLS is enabled by default for client access. The server-side API should use
-- a rotated Supabase secret/service-role key; those keys bypass RLS.
alter table public.menu_categories enable row level security;
alter table public.menu_items enable row level security;
alter table public.orders enable row level security;
alter table public.order_items enable row level security;

drop policy if exists public_read_categories on public.menu_categories;
create policy public_read_categories
on public.menu_categories for select
to anon, authenticated
using (true);

drop policy if exists public_read_available_menu on public.menu_items;
create policy public_read_available_menu
on public.menu_items for select
to anon, authenticated
using (available = true);

