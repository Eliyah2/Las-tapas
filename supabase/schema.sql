-- Enable Supabase Realtime for the kitchen screen. If this statement is already
-- present in the publication, the DO block leaves it unchanged.
do $$
begin
  begin
    alter publication supabase_realtime add table public.orders;
  exception
    when duplicate_object then null;
  end;
end;
$$;

-- Useful view for the kitchen/API.
create or replace view public.orders_with_items
with (security_invoker = true)
as
select
  o.id,
  o.table_number,
  o.status,
  o.note,
  o.created_at,
  o.updated_at,
  coalesce(
    jsonb_agg(
      jsonb_build_object(
        'id', oi.menu_item_id,
        'name', oi.name,
        'price', oi.price,
        'quantity', oi.quantity
      ) order by oi.id
    ) filter (where oi.id is not null),
    '[]'::jsonb
  ) as items
from public.orders o
left join public.order_items oi on oi.order_id = o.id
group by o.id;
